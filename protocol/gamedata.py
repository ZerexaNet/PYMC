"""
Lazy loaders for the vanilla data tables bundled in ``protocol/data``.

The JSON files are generated by ``tools/gen_protocol_data.py`` from
PrismarineJS minecraft-data and misode/mcmeta. They provide the pieces a real
1.21.1 client expects from a real server and which cannot be hand-written
reliably: synchronised registries, tags, the item ID table, the brigadier
command tree and an en_us language subset used to render translatable
messages on the console.
"""

from __future__ import annotations

import json
import struct
import sys
from functools import lru_cache
from pathlib import Path
from typing import Any

DATA_VERSION = 767


def _data_dir_candidates() -> list[Path]:
    here = Path(__file__).resolve().parent
    return [
        here / "data",
        Path(sys.argv[0]).resolve().parent / "protocol" / "data",
        Path("protocol") / "data",
    ]


@lru_cache(maxsize=None)
def load_data(name: str) -> Any:
    """Load ``protocol/data/<name>`` (source tree, Nuitka bundle or CWD)."""
    for directory in _data_dir_candidates():
        path = directory / name
        if path.exists():
            with path.open("r", encoding="utf-8") as f:
                return json.load(f)
    raise FileNotFoundError(
        f"Cannot find protocol data file {name!r}; "
        f"searched {[str(d) for d in _data_dir_candidates()]}"
    )


# ------------------------------------------------------------------
# Typed NBT JSON ({"type": ..., "value": ...}) -> binary NBT
# ------------------------------------------------------------------

_TAG_IDS = {
    "end": 0, "byte": 1, "short": 2, "int": 3, "long": 4, "float": 5,
    "double": 6, "byteArray": 7, "string": 8, "list": 9, "compound": 10,
    "intArray": 11, "longArray": 12,
}


def _long_value(value) -> int:
    # prismarine-nbt stores longs as [high, low] int pairs.
    if isinstance(value, (list, tuple)):
        high, low = value
        value = ((high & 0xFFFFFFFF) << 32) | (low & 0xFFFFFFFF)
    value &= 0xFFFFFFFFFFFFFFFF
    return value - (1 << 64) if value >= (1 << 63) else value


def _nbt_string(text: str) -> bytes:
    raw = text.encode("utf-8")
    return struct.pack(">H", len(raw)) + raw


def _typed_payload(tag_type: str, value) -> bytes:
    if tag_type == "byte":
        return struct.pack(">b", ((int(value) + 128) & 0xFF) - 128)
    if tag_type == "short":
        return struct.pack(">h", int(value))
    if tag_type == "int":
        return struct.pack(">i", int(value))
    if tag_type == "long":
        return struct.pack(">q", _long_value(value))
    if tag_type == "float":
        return struct.pack(">f", float(value))
    if tag_type == "double":
        return struct.pack(">d", float(value))
    if tag_type == "string":
        return _nbt_string(value)
    if tag_type == "byteArray":
        return struct.pack(">i", len(value)) + bytes((int(v) & 0xFF) for v in value)
    if tag_type == "intArray":
        return struct.pack(">i", len(value)) + b"".join(struct.pack(">i", int(v)) for v in value)
    if tag_type == "longArray":
        return struct.pack(">i", len(value)) + b"".join(
            struct.pack(">q", _long_value(v)) for v in value)
    if tag_type == "list":
        inner_type = value["type"]
        items = value["value"]
        out = bytearray([_TAG_IDS[inner_type]])
        out += struct.pack(">i", len(items))
        for item in items:
            out += _typed_payload(inner_type, item)
        return bytes(out)
    if tag_type == "compound":
        out = bytearray()
        for key, child in value.items():
            out.append(_TAG_IDS[child["type"]])
            out += _nbt_string(key)
            out += _typed_payload(child["type"], child["value"])
        out.append(0)
        return bytes(out)
    raise ValueError(f"unsupported NBT tag type: {tag_type}")


def encode_typed_nbt(node: dict) -> bytes:
    """Encode a typed-JSON NBT node as nameless network NBT."""
    return bytes([_TAG_IDS[node["type"]]]) + _typed_payload(node["type"], node["value"])


# ------------------------------------------------------------------
# Registries
# ------------------------------------------------------------------

def _biome_order(vanilla_names: list[str]) -> list[str]:
    """Keep PyMC's saved biome indices stable; append the rest of vanilla."""
    try:
        from world.biomes import BIOME_NAME_TO_ID
    except Exception:  # pragma: no cover - defensive
        return vanilla_names
    known = [n for n, _ in sorted(BIOME_NAME_TO_ID.items(), key=lambda kv: kv[1])]
    ordered = [n for n in known if n in set(vanilla_names)]
    if ordered != known:
        # A PyMC biome is missing from vanilla data: indices would shift.
        raise RuntimeError("world.biomes contains biomes unknown to 1.21.1")
    extra = [n for n in vanilla_names if n not in set(known)]
    return ordered + extra


@lru_cache(maxsize=None)
def synced_registries() -> dict[str, list[tuple[str, bytes]]]:
    """
    Registries sent during configuration.

    Returns ``{registry_id: [(entry_id, nbt_bytes), ...]}``; list position is
    the numeric ID the client assigns to the entry.
    """
    raw = load_data("registries_767.json")
    result: dict[str, list[tuple[str, bytes]]] = {}
    for registry_id, entries in raw.items():
        names = list(entries.keys())
        if registry_id == "minecraft:worldgen/biome":
            names = _biome_order(names)
        result[registry_id] = [(name, encode_typed_nbt(entries[name])) for name in names]
    return result


@lru_cache(maxsize=None)
def registry_index(registry_id: str) -> dict[str, int]:
    """``{entry_id: numeric_id}`` for a synchronised registry."""
    return {name: i for i, (name, _) in enumerate(synced_registries()[registry_id])}


@lru_cache(maxsize=None)
def tags() -> dict[str, dict[str, list[int]]]:
    """``{registry: {tag: [numeric ids]}}`` for the Update Tags packet."""
    raw = load_data("tags_767.json")
    result: dict[str, dict[str, list[int]]] = {}
    for registry_id, registry_tags in raw.items():
        sample = next((v for v in registry_tags.values() if v), [])
        if sample and isinstance(sample[0], str):
            index = registry_index(registry_id)
            result[registry_id] = {
                tag: [index[v] for v in values if v in index]
                for tag, values in registry_tags.items()
            }
        else:
            result[registry_id] = registry_tags
    return result


# ------------------------------------------------------------------
# Items / entity types
# ------------------------------------------------------------------

@lru_cache(maxsize=None)
def item_names() -> list[str]:
    """Item identifiers (namespaced) indexed by protocol ID."""
    return ["minecraft:" + n for n in load_data("items_767.json")["names"]]


@lru_cache(maxsize=None)
def item_ids() -> dict[str, int]:
    return {name: i for i, name in enumerate(item_names())}


@lru_cache(maxsize=None)
def item_stack_sizes() -> dict[str, int]:
    return {"minecraft:" + k: v for k, v in load_data("items_767.json")["stack_sizes"].items()}


@lru_cache(maxsize=None)
def item_durability() -> dict[str, int]:
    return {"minecraft:" + k: v for k, v in load_data("items_767.json")["durability"].items()}


@lru_cache(maxsize=None)
def entity_type_ids() -> dict[str, int]:
    return {"minecraft:" + n: i for i, n in enumerate(load_data("entity_types_767.json"))}


@lru_cache(maxsize=None)
def language() -> dict[str, str]:
    """en_us subset used to print translatable components on the console."""
    try:
        return load_data("lang_en_us.json")
    except FileNotFoundError:
        return {}
